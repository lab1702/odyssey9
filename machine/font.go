package machine

// The Odyssey2 character generator holds 64 symbols (the manual's
// "Computer Symbols" chart shows codes 00-3E). Each glyph is 8 pixels wide
// and 7 rows tall. These bitmaps were drawn to match the chart in the
// manual's back gatefold.

// GlyphWidth and GlyphHeight are the dimensions of a character cell.
const (
	GlyphWidth  = 8
	GlyphHeight = 7
)

// Glyph returns the 7 row bitmaps for a character code. Bit 7 is the
// leftmost pixel. Codes outside the character set render as blank.
func Glyph(code byte) [GlyphHeight]byte {
	if int(code) >= len(glyphs) {
		return [GlyphHeight]byte{}
	}
	return glyphs[code]
}

var glyphs = func() [64][GlyphHeight]byte {
	var g [64][GlyphHeight]byte
	for code, rows := range glyphArt {
		for y, row := range rows {
			var b byte
			for x := 0; x < len(row) && x < GlyphWidth; x++ {
				if row[x] == '#' {
					b |= 0x80 >> x
				}
			}
			g[code][y] = b
		}
	}
	return g
}()


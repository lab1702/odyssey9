// asciiToCode maps the printable characters used by the emulator's status
// line onto the Odyssey2 character set.
var asciiToCode = func() map[rune]byte {
	m := map[rune]byte{
		' ': 0x0C, ':': 0x0A, '$': 0x0B, '?': 0x0D, '+': 0x10, '.': 0x27,
		'-': 0x28, '*': 0x29, '=': 0x2B, '/': 0x2E, '#': 0x2F,
	}
	for d := 0; d <= 9; d++ {
		m[rune('0'+d)] = byte(d)
	}
	for code, ch := range codeLetters {
		m[ch] = code
	}
	return m
}()

var codeLetters = map[byte]rune{
	0x0E: 'L', 0x0F: 'P', 0x11: 'W', 0x12: 'E', 0x13: 'R', 0x14: 'T',
	0x15: 'U', 0x16: 'I', 0x17: 'O', 0x18: 'Q', 0x19: 'S', 0x1A: 'D',
	0x1B: 'F', 0x1C: 'G', 0x1D: 'H', 0x1E: 'J', 0x1F: 'K', 0x20: 'A',
	0x21: 'Z', 0x22: 'X', 0x23: 'C', 0x24: 'V', 0x25: 'B', 0x26: 'M',
	0x2C: 'Y', 0x2D: 'N',
}

// CharCode converts an ASCII character to an Odyssey2 character code.
// Unknown characters become a blank.
func CharCode(r rune) byte {
	if r >= 'a' && r <= 'z' {
		r -= 'a' - 'A'
	}
	if c, ok := asciiToCode[r]; ok {
		return c
	}
	return 0x0C
}

// TextCodes converts a string to Odyssey2 character codes.
func TextCodes(s string) []byte {
	out := make([]byte, 0, len(s))
	for _, r := range s {
		out = append(out, CharCode(r))
	}
	return out
}
